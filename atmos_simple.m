function [a, rho] = atmos_simple(h)
% 标准大气模型（基于几何高度分段，严格按图片公式）
% 输入: h - 几何高度，单位 m
% 输出: a - 声速，m/s； rho - 密度，kg/m^3

%% 常数定义
R0_km = 6356.766;      % 地球半径，km
p0 = 101325;           % 海平面压强，Pa
rho0 = 1.225;          % 海平面密度，kg/m^3
R = 287;               % 空气气体常数，J/(kg·K)
gamma = 1.4;           % 比热比

%% 转换为千米
h_km = h / 1000;

%% 计算地势高度 H (km)
H_km = h_km / (1 + h_km / R0_km);

%% 分段计算
if h_km <= 11.019
    % 第一段：0 ~ 11.019 km
    W = 1 - H_km / 44.3308;
    T = 288.15 * W;
    p = W^2.2559 * p0;
    rho = W^4.2559 * rho0;

elseif h_km <= 20.0631
    % 第二段：11.0191 ~ 20.0631 km
    W = exp((14.9647 - H_km) / 6.3416);
    T = 216.65;
    p = 0.11953 * W * p0;
    rho = 0.15898 * W * rho0;

elseif h_km <= 32.1619
    % 第三段：20.0631 ~ 32.1619 km
    W = 1 + (H_km - 24.9021) / 221.552;
    T = 211.552 * W;
    p = 0.025158 * W^(-3.4169) * p0;
    rho = 0.032722 * W^(-3.5169) * rho0;

elseif h_km <= 47.3501
    % 第四段：32.1619 ~ 47.3501 km（使用显式密度公式）
    W = 1 + (H_km - 39.7499) / 89.4107;
    T = 250.350 * W;
    p = 2.8338e-3 * W^(-12.2011) * p0;
    rho = 3.2618e-3 * W^(-13.2021) * rho0;   % 修正点

else
    % 超出模型范围（>47.35 km），简单外推
    % 使用第四段末端值等温指数衰减
    H_end = 47.3501e3;   % 几何高度 m
    % 计算末端的大气参数（第四段终点）
    W_end = 1 + ( (47.3501 - 39.7499) / 89.4107 );   % 注意：H_km 在终点 = H_km_end，此处简化用几何高度代入地势公式？为简化，直接用几何高度47.3501km对应的H。更精确应计算，但外推影响不大。
    % 简便处理：直接取第四段末端温度
    T_end = 250.350 * W_end;
    p_end = 2.8338e-3 * W_end^(-12.2011) * p0;
    rho_end = 3.2618e-3 * W_end^(-13.2021) * rho0;
    % 指数衰减
    H_scale = 7000;   % 标高，m
    p = p_end * exp(-(h - H_end) / H_scale);
    T = T_end;
    rho = rho_end * exp(-(h - H_end) / H_scale);
end

%% 声速计算
a = sqrt(gamma * R * T);   % m/s
end