function [CT] = thrust_coeffs(Ma, alpha, dT)
% alpha, beta使用度要统一
adeg = alpha*180/pi;

%  C_Tc = C_Tc(Ma,α,β,δ_T)  
CTc =  0.1029      * dT ...
     - 0.02022     * Ma * dT ...
     - 0.001757    * adeg  * dT ...
     + 0.000088233 * adeg.^2 * dT ...
     + 0.001221    * Ma.^2 .* dT;

%  C_Tn = C_Tn(Ma,α,β,δ_T)  
CTn =  0.03791 ...
     + 0.005176   * adeg ...
     - 0.01235    * Ma ...
     - 0.00054887 * Ma* adeg ...
     + 0.00096897 * Ma.^2 ...
     + 0.05627    * dT ...
     - 0.00077467 * (adeg * dT) ...
     + 0.002103   * (Ma *  dT);
CT = CTc + CTn;

end