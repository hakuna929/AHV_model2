function [CL, CD, CT] = aero_coeffs(Ma, alpha, dT)
% 3DOF简化版气动系数
% 目的：3DOF不考虑舵偏动态影响 -> 舵偏输入不参与CL/CD/CY（固定为配平思想）
% 输入:
%   Ma, alpha(rad),dT
% 输出:
%   CL,CD,CT 参与3DOF平动

    %% -------- 单位转换 --------
    % adeg = alpha * 180/pi;
    adeg = alpha;


    %% -------- 输入限幅（数值稳定）--------
    Ma   = min(max(Ma,   0.0), 8.0);
    adeg = min(max(adeg,-2.0), 10.0);

    %% -------- 升力系数 CL（仅Ma,alpha）--------
    % 原模型去舵偏后的主体项：
    CLa = 0.1498 ...
        - 0.02751 * Ma ...
        + 0.07235 * adeg ...
        - 0.003368 * adeg * Ma ...
        + 0.002343 * Ma.^2 ...
        + 0.001185 * adeg.^2;

    % C_Le = C_Le(Ma, alpha, delta_T)
    CLe = 0.7215 ...
        + 0.02635  * adeg ...
        + 0.1147   * Ma ...
        - 0.002795 * Ma * adeg ...
        - 0.5782   * sqrt(Ma) ...
        + 0.2894   * dT ...
        - 0.004363 * adeg * dT ...
        + 0.01083  * Ma * dT;




    %% -------- 阻力系数 CD（仅Ma,alpha）--------
    % CDa(Ma, alpha)
    CDa = 0.05099 ...
        - 0.004863 * Ma ...
        + 0.002967 * adeg ...
        + 0.001364 * adeg.^2;

    % C_De = C_De(Ma, alpha, delta_T)
    CDe = 0.002339 * adeg ...
        + 0.00012182 * adeg.^2 ...
        - 0.00033126 * Ma * adeg ...
        + 0.005557 * adeg * dT;


    CL = CLa + CLe;
    CD = CDa + CDe;

    %% -------- 系数硬限幅（防数值炸裂）--------
    CL = min(max(CL, -2.2), 2.2);
    CD = min(max(CD,  0.015), 1.2);

    %  C_Tc = C_Tc(Ma,α,δ_T)
    CTc =  0.1029      * dT ...
        - 0.02022     * Ma * dT ...
        - 0.001757    * adeg  * dT ...
        + 0.000088233 * adeg.^2 * dT ...
        + 0.001221    * Ma.^2 .* dT;

    %  C_Tn = C_Tn(Ma,α,δ_T)
    CTn =  0.03791 ...
        + 0.005176   * adeg ...
        - 0.01235    * Ma ...
        - 0.00054887 * Ma* adeg ...
        + 0.00096897 * Ma.^2 ...
        + 0.05627    * dT ...
        - 0.00077467 * (adeg * dT) ...
        + 0.002103   * Ma  * dT;

    CT = CTc + CTn;
end