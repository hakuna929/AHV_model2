    CL = 0.1498 ...
       - 0.02751 * Ma ...
       + 0.07235 * adeg ...
       - 0.003368 * adeg * Ma ...
       + 0.002343 * Ma.^2 ...
       + 0.001185 * adeg.^2;

    %% -------- 阻力系数 CD（仅Ma,alpha）--------
    CD = 0.05099 ...
       - 0.004863 * Ma ...
       + 0.002967 * adeg ...
       + 0.001364 * adeg.^2;


